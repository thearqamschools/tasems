"""Student ID cards (M4): credit-card size, ten to an A4 sheet, with photo and admission-number barcode."""

import io

from barcode import Code128
from barcode.writer import SVGWriter
from django.conf import settings
from django.template.loader import render_to_string
from django.utils.safestring import mark_safe

from apps.diary.models import DiaryLayout


def admission_barcode(number):
    buffer = io.BytesIO()
    Code128(str(number), writer=SVGWriter()).write(
        buffer, options={"module_height": 7, "module_width": 0.22, "quiet_zone": 1, "write_text": False}
    )
    svg = buffer.getvalue().decode()
    return mark_safe(svg[svg.index("<svg") :])  # noqa: S308 (generated by python-barcode, no user text)


def render_pdf(branch, session, cards):
    """`cards` = [(student, section or None)]."""
    from weasyprint import HTML

    html = render_to_string(
        "people/id_cards.html",
        {
            "branch": branch,
            "session": session,
            "cards": [
                {
                    "s": student,
                    "section": section,
                    "photo": f"file://{student.photo.path}" if student.photo else "",
                    "barcode": admission_barcode(student.admission_no),
                }
                for student, section in cards
            ],
            "layout": DiaryLayout.current(),
            "font_base": f"file://{settings.BASE_DIR}/static/fonts/",
            "media_base": f"file://{settings.MEDIA_ROOT}/",
        },
    )
    return HTML(string=html, base_url=str(settings.BASE_DIR)).write_pdf()
